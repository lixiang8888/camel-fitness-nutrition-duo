#: 上游那份 OCR 里没有、改用 USDA 补的食物。
#:
#: **只补「单一原料、成分跨地区稳定」的**，生鲜水果是典型。配方类产品
#: （面包、花生酱）故意不补——美式配方和中式产品差得远（美国花生酱普遍加糖和
#: 氢化油，中国花生酱通常就是纯花生），拿美国的数字挂中文名，正是本模块
#: 最想避免的「精确的错」。这类东西的正确答案是「查不到，看包装背标」，
#: 而那恰好是读者唯一能拿到准确数字的地方。
#:
#: 芝麻酱是个说得通的例外：它和 USDA 的 roasted tahini 是同一种东西——
#: 烘烤芝麻研磨，单一原料，没有配方差异。它在「火锅局」那个议题里是硬需求，
#: 缺了它手册只能留个洞。
#:
#: 数值取自 USDA FoodData Central 的 SR Legacy 数据集（**公有领域**），
#: 末列的 fdcId 可以直接在 https://fdc.nal.usda.gov 上核。
#: (规范名, 别名, 分类, 能量kcal, 蛋白, 脂肪, 碳水, 纤维, 钠mg, fdcId)
USDA_PICKS: list[tuple[str, str, str, float, float, float, float, float, float, int]] = [
    ("蓝莓", "blueberry|越橘", "水果", 57.0, 0.74, 0.33, 14.5, 2.4, 1.0, 171711),
    ("芝麻酱", "麻酱|纯芝麻酱", "坚果种子", 595.0, 17.0, 53.8, 21.2, 9.3, 115.0, 170189),
]

USDA_SOURCE_LABEL = "USDA FoodData Central (SR Legacy)"


def norm(value: object) -> str:
    """成分表里的占位符归一成数字。

    原书用 `Tr` 表示微量、`—` 表示未测定、`un` 表示未知，数字后面带 `*`
    表示这是计算值。这些都写成 0，并在 README 里说明——留着原样会让
    CSV 的列一半是字符串一半是数字，Excel 里没法排序。
    """
    if value is None:
        return ""
    text = str(value).strip().rstrip("*")
    if text in ("Tr", "tr", "—", "-", "", "…", "un", "UN"):
        return "0"
    try:
        return f"{float(text):.1f}"
    except ValueError:
        return ""


def fetch(dest: str) -> int:
    """把类别 JSON 下到 dest。返回可用数（含缓存命中的）。

    已经在 dest 里的就跳过——GitHub 匿名 API 每小时只给 60 次，
    而这份清单有 30 多个文件，重跑一次就撞墙了。
    """
    base = f"https://api.github.com/repos/{REPO}/contents/{DATA_DIR}"
    ok = 0
    for name in CATEGORY_FILES:
        target = os.path.join(dest, name)
        if os.path.exists(target) and os.path.getsize(target) > 0:
            ok += 1
            continue
        url = f"{base}/{urllib.parse.quote(name)}"
        request = urllib.request.Request(url, headers={"User-Agent": "food-table-build/1.0"})
        try:
            with urllib.request.urlopen(request, timeout=60) as response:
                payload = json.load(response)
            with open(target, "wb") as handle:
                handle.write(base64.b64decode(payload["content"]))
            ok += 1
        except Exception as exc:  # noqa: BLE001 - 网络问题就地报出来继续下一份
            print(f"  失败 {name}: {exc}")
        time.sleep(0.3)  # 别去撞 GitHub 的速率限制
    return ok


def build(src: str, out: str) -> list[str]:
    """把 dest 里的 JSON 摘成 CSV。返回没找到的条目。"""
    index: dict[str, dict] = {}
    for name in CATEGORY_FILES:
        path = os.path.join(src, name)
        if not os.path.exists(path):
            continue
        with open(path, encoding="utf-8") as handle:
            for record in json.load(handle):
                index.setdefault(record.get("foodName", ""), record)

    rows, missed = [], []
    for name, alias, category, source_name in PICKS:
        record = index.get(source_name)
        if record is None:
            missed.append(f"{name}  <-  {source_name}")
            continue
        rows.append({
            "name": name,
            "alias": alias,
            "category": category,
            "edible_pct": norm(record.get("edible")),
            "energy_kcal": norm(record.get("energyKCal")),
            "protein_g": norm(record.get("protein")),
            "fat_g": norm(record.get("fat")),
            "carb_g": norm(record.get("CHO")),
            "fiber_g": norm(record.get("dietaryFiber")),
            "sodium_mg": norm(record.get("Na")),
            "source": SOURCE_LABEL,
            "src_code": record.get("foodCode", ""),
        })

    for name, alias, category, kcal, protein, fat, carb, fiber, sodium, fdc_id in USDA_PICKS:
        rows.append({
            "name": name,
            "alias": alias,
            "category": category,
            "edible_pct": "100.0",
            "energy_kcal": f"{kcal:.1f}",
            "protein_g": f"{protein:.1f}",
            "fat_g": f"{fat:.1f}",
            "carb_g": f"{carb:.1f}",
            "fiber_g": f"{fiber:.1f}",
            "sodium_mg": f"{sodium:.1f}",
            "source": USDA_SOURCE_LABEL,
            "src_code": f"fdcId {fdc_id}",
        })

    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    # utf-8-sig：带 BOM。这样在 Windows 上双击用 Excel 打开不会乱码，
    # fooddata.py 读的时候用 "utf-8-sig"，两种编码都能吃。
    with open(out, "w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    print(f"写出 {len(rows)} 行 -> {out}")
    return missed


def main() -> int:
    out = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_OUT
    cache = CACHE_DIR
    os.makedirs(cache, exist_ok=True)

    print(f"下载 {len(CATEGORY_FILES)} 个类别文件…")
    got = fetch(cache)
    print(f"  成功 {got}/{len(CATEGORY_FILES)}")
    if got == 0:
        print("一份都没下下来，检查网络。")
        return 1

    missed = build(cache, out)
    if missed:
        print(f"有 {len(missed)} 条在上游找不到（原书改名了？）：")
        for item in missed:
            print("  ", item)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
