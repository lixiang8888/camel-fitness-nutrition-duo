"""两位智能体的人格设定。

这是整个项目的「戏眼」：两个人格的分歧必须是真的分歧，产出才有价值。
分歧轴 = 循证最优  vs  现实中做得到。
如果两个人格只是互相附和，对话会退化成复读机，最后的手册也就没有信息量。
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Persona:
    name: str
    title: str
    system_message: str


