# 收尾议题：不产出正文章节，而是产出「分歧备忘录 + 自检清单」。
# 这是双人格对话相比单人输出的核心增量——把「哪里没谈拢」也交付给读者。
CLOSING_TOPIC = Topic(
    key="closing",
    section_title="附录：双教练分歧备忘 · 红线信号 · 每日自检清单",
    brief=(
        "收尾讨论：回顾前面五个议题，哪些地方你们真正达成了共识，"
        "哪些地方你们仍然保留不同意见。以及普通人最容易踩的红线信号有哪些。"
    ),
    goal="如实记录未解决的分歧（不要强行和稀泥），并产出一份可以每天勾选的自检清单。",
    opening=(
        "【结论先行】我们前面谈了五个议题。我想先确认一件事："
        "哪些结论是我们都真的认同的，哪些只是我们各自让步的结果。\n\n"
        "让步出来的方案如果不写明代价，读者会以为它是免费的。"
    ),
)


def get_topic(key: str) -> Topic:
    for topic in (*TOPICS, CLOSING_TOPIC):
        if topic.key == key:
            return topic
    valid = ", ".join(t.key for t in (*TOPICS, CLOSING_TOPIC))
    raise KeyError(f"未知议题 {key!r}，可选：{valid}")
